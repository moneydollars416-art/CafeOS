export function useT() {
  const language = useContext(LanguageContext);
  return key => translations[language]?.[key] ?? translations.ru[key] ?? key;
}
export function useFoodText() {
  const t = useT();
  const pick = (prefix, text) => {
    const key = `${prefix}.${text}`;
    const value = t(key);
    return value === key ? text : value;
  };
  return {
    dish: name => pick("dish", name),
    desc: text => pick("desc", text)
  };
}